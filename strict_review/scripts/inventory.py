#!/usr/bin/env python3
"""Read-only inventory for the strict_review skill.

Prints where a codebase's mass, debt markers, escape hatches and dependency tangles
sit, so the audit knows where to read first. Writes nothing. Every number is a lead
to read, never a finding by itself.

    python inventory.py [ROOT] [--top N] [--depth N] [--exclude GLOB ...] [--no-deps]

Files come from `git ls-files` when ROOT is inside a git work tree (so .gitignore is
respected), otherwise from a directory walk. Vendored and hidden directories are always
skipped; files that declare themselves generated are counted but kept out of the size
and marker statistics.

The dependency graph is heuristic. It resolves Python imports, JS/TS relative imports
(plus `paths`/`baseUrl` from the nearest tsconfig/jsconfig), Go imports within a
module, and Dart relative and `package:` imports. Other languages appear in the size
statistics only.
"""

