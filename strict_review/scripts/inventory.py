# ---------------------------------------------------------------- file discovery

def list_files(root: Path) -> tuple[list[str], str]:
    try:
        proc = subprocess.run(
            ["git", "-C", str(root), "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            capture_output=True, check=True,
        )
        paths = [p for p in proc.stdout.decode("utf-8", "replace").split("\0") if p]
        return [p for p in paths if not skipped(p, ALWAYS_SKIP) and (root / p).is_file()], "git ls-files"
    except (OSError, subprocess.CalledProcessError):
        pass
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in WALK_SKIP and not d.startswith(".")]
        rel_dir = Path(dirpath).relative_to(root).as_posix()
        for name in filenames:
            found.append(name if rel_dir == "." else f"{rel_dir}/{name}")
    return found, "directory walk"


def skipped(path: str, skip_dirs: set[str]) -> bool:
    dirs = path.split("/")[:-1]
    return any(d in skip_dirs or d.startswith(".") for d in dirs)


# ---------------------------------------------------------------- per-file facts

class FileFacts:
    __slots__ = ("path", "lang", "text", "lines", "is_test", "generated",
                 "markers", "suppressions", "escapes", "deep")

    def __init__(self, path: str, lang: str, text: str):
        self.path, self.lang, self.text = path, lang, text
        lines = text.splitlines()
        self.lines = len(lines)
        self.is_test = bool(TEST_PATH.search(path))
        avg = (len(text) / self.lines) if self.lines else 0
        self.generated = bool(GENERATED_NAME.search(path) or GENERATED_HEADER.search(text[:1500]) or avg > 400)
        self.markers = len(MARKERS.findall(text))
        self.suppressions = Counter(m.group(0).strip() for m in SUPPRESSIONS.finditer(text))
        hatch = ESCAPE_HATCHES.get(lang)
        self.escapes = len(hatch.findall(text)) if hatch else 0
        self.deep = deep_line_count(lines)


def deep_line_count(lines: list[str]) -> int:
    """Lines indented DEEP_LEVELS or more levels — a language-agnostic nesting proxy."""
    widths = []
    for line in lines:
        body = line.lstrip(" \t")
        if not body or body.startswith(("*", "//", "#", "<!--", "--")):
            continue
        lead = line[: len(line) - len(body)]
        widths.append(lead.count("\t") * 4 + lead.count(" "))
    positive = Counter(w for w in widths if w)
    if not positive:
        return 0
    common = [w for w, n in positive.items() if n >= 3] or list(positive)
    step = max(2, min(min(common), 8))
    return sum(1 for w in widths if w >= DEEP_LEVELS * step)


def read_text(path: Path) -> str | None:
    try:
        if path.stat().st_size > MAX_BYTES:
            return None
        raw = path.read_bytes()
    except OSError:
        return None
    if b"\0" in raw[:8192]:
        return None
    return raw.decode("utf-8", "replace")


# ---------------------------------------------------------------- dependency graph

def strip_jsonc(text: str) -> str:
    out, i, in_str = [], 0, False
    while i < len(text):
        ch = text[i]
        if in_str:
            out.append(ch)
            if ch == "\\" and i + 1 < len(text):
                out.append(text[i + 1])
                i += 1
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
            out.append(ch)
        elif text.startswith("//", i):
            while i < len(text) and text[i] != "\n":
                i += 1
            continue
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = len(text) if end < 0 else end + 2
            continue
        else:
            out.append(ch)
        i += 1
    return re.sub(r",\s*([}\]])", r"\1", "".join(out))


def load_ts_configs(root: Path, files: list[str]) -> dict[str, tuple[str, dict]]:
    """Map each tsconfig/jsconfig directory to (baseUrl dir, paths)."""
    configs = {}
    for f in files:
        if posixpath.basename(f) not in ("tsconfig.json", "jsconfig.json"):
            continue
        text = read_text(root / f)
        try:
            opts = json.loads(strip_jsonc(text or "")).get("compilerOptions", {}) or {}
        except (ValueError, AttributeError):
            continue
        cfg_dir = posixpath.dirname(f)
        if "baseUrl" not in opts and "paths" not in opts:
            continue
        base = posixpath.normpath(posixpath.join(cfg_dir, opts.get("baseUrl", ".")))
        configs[cfg_dir] = (base, opts.get("paths", {}) or {})
    return configs


def nearest_config(path: str, configs: dict) -> tuple[str, dict] | None:
    d = posixpath.dirname(path)
    while True:
        if d in configs:
            return configs[d]
        if d in ("", "."):
            return configs.get("") or configs.get(".")
        d = posixpath.dirname(d)


def resolve_js(src: str, spec: str, files: set[str], configs: dict) -> str | None:
    """Return the internal file `spec` resolves to, "?" if internal but unresolved, None if external."""
    bases = []
    if spec.startswith("."):
        bases.append(posixpath.normpath(posixpath.join(posixpath.dirname(src), spec)))
    else:
        cfg = nearest_config(src, configs)
        if cfg:
            base_dir, paths = cfg
            for pattern, targets in paths.items():
                prefix, star, suffix = pattern.partition("*")
                if star and spec.startswith(prefix) and spec.endswith(suffix):
                    rest = spec[len(prefix): len(spec) - len(suffix) if suffix else None]
                    bases += [posixpath.normpath(posixpath.join(base_dir, t.replace("*", rest))) for t in targets]
                elif not star and spec == pattern:
                    bases += [posixpath.normpath(posixpath.join(base_dir, t)) for t in targets]
            bases.append(posixpath.normpath(posixpath.join(base_dir, spec)))
    for base in bases:
        stem = re.sub(r"\.[cm]?jsx?$", "", base)
        for cand in (base, *(stem + e for e in JS_EXTS), *(f"{base}/index{e}" for e in JS_EXTS)):
            if cand in files:
                return cand
    return "?" if spec.startswith(".") else None


def python_index(py_files: list[str]) -> tuple[dict[str, str], dict[str, str]]:
    roots = {""} | {p[: p.index("/src/") + 5] for p in py_files if "/src/" in p}
    roots |= {"src/"} if any(p.startswith("src/") for p in py_files) else set()
    module_to_file, file_to_module = {}, {}
    for root in sorted(roots, key=len, reverse=True):
        for p in py_files:
            if not p.startswith(root) or p in file_to_module:
                continue
            mod = p[len(root):].rsplit(".", 1)[0].replace("/", ".")
            if mod.endswith(".__init__") or mod == "__init__":
                mod = mod[: -len("__init__")].rstrip(".")
            if mod:
                module_to_file.setdefault(mod, p)
                file_to_module[p] = mod
    return module_to_file, file_to_module


def resolve_py_module(name: str, index: dict[str, str]) -> str | None:
    parts = name.split(".")
    for n in range(len(parts), 0, -1):
        hit = index.get(".".join(parts[:n]))
        if hit:
            return hit
    return None


def python_imports(src: str, text: str, index: dict, file_to_module: dict) -> list[str]:
    targets = []
    for line in PY_IMPORT.finditer(text):
        for item in line.group(1).split(","):
            name = item.strip().split(" as ")[0].strip()
            hit = resolve_py_module(name, index) if name else None
            if hit:
                targets.append(hit)
    for m in PY_FROM.finditer(text):
        dots, mod, names = m.group(1), m.group(2), m.group(3)
        if dots:
            me = file_to_module.get(src, "")
            pkg = me.split(".") if src.endswith("__init__.py") else me.split(".")[:-1]
            keep = len(pkg) - (len(dots) - 1)
            if keep < 0:
                continue
            mod = ".".join([*pkg[:keep], *([mod] if mod else [])])
        if not mod:
            continue
        hits = [index.get(f"{mod}.{n.strip().split(' as ')[0].strip()}") for n in names.split(",")]
        hits = [h for h in hits if h]
        targets += hits or [h for h in [resolve_py_module(mod, index)] if h]
    return targets


def go_modules(root: Path, files: list[str]) -> list[tuple[str, str]]:
    mods = []
    for f in files:
        if posixpath.basename(f) == "go.mod":
            m = re.search(r"^module\s+(\S+)", read_text(root / f) or "", re.M)
            if m:
                mods.append((m.group(1), posixpath.dirname(f)))
    return sorted(mods, key=lambda x: len(x[0]), reverse=True)


def go_imports(text: str, modules: list[tuple[str, str]]) -> list[str]:
    specs = GO_SINGLE.findall(text)
    for block in GO_BLOCK.findall(text):
        specs += GO_PATH.findall(block)
    dirs = []
    for spec in specs:
        for mod, mod_dir in modules:
            if spec == mod or spec.startswith(mod + "/"):
                rel = spec[len(mod):].lstrip("/")
                dirs.append(posixpath.normpath(posixpath.join(mod_dir, rel)) if rel or mod_dir else ".")
                break
    return dirs


def dart_packages(root: Path, files: list[str]) -> dict[str, str]:
    """Map each pubspec package name to its lib/ directory."""
    packages = {}
    for f in files:
        if posixpath.basename(f) == "pubspec.yaml":
            m = re.search(r"^name:\s*([\w]+)", read_text(root / f) or "", re.M)
            if m:
                packages[m.group(1)] = posixpath.join(posixpath.dirname(f), "lib").lstrip("/")
    return packages


def dart_imports(src: str, text: str, packages: dict[str, str], files: set[str]) -> list[str]:
    targets = []
    for spec in DART_IMPORT.findall(text):
        if spec.startswith("dart:"):
            continue
        if spec.startswith("package:"):
            name, _, rest = spec[len("package:"):].partition("/")
            if name not in packages:
                continue
            target = posixpath.normpath(posixpath.join(packages[name], rest))
        else:
            target = posixpath.normpath(posixpath.join(posixpath.dirname(src), spec))
        if target in files:
            targets.append(target)
    return targets


def unit_of(path: str, depth: int, is_dir: bool = False) -> str:
    d = path if is_dir else posixpath.dirname(path)
    parts = [p for p in d.split("/") if p and p != "."]
    return "/".join(parts[:depth]) or "."


def strongly_connected(graph: dict[str, set[str]]) -> list[list[str]]:
    """Tarjan's algorithm, iterative. Returns components with more than one node."""
    index, low, on_stack, stack, result, counter = {}, {}, set(), [], [], 0
    for start in list(graph):
        if start in index:
            continue
        index[start] = low[start] = counter
        counter += 1
        stack.append(start)
        on_stack.add(start)
        work = [(start, iter(graph.get(start, ())))]
        while work:
            node, children = work[-1]
            for child in children:
                if child not in index:
                    index[child] = low[child] = counter
                    counter += 1
                    stack.append(child)
                    on_stack.add(child)
                    work.append((child, iter(graph.get(child, ()))))
                    break
                if child in on_stack:
                    low[node] = min(low[node], index[child])
            else:
                work.pop()
                if work:
                    parent = work[-1][0]
                    low[parent] = min(low[parent], low[node])
                if low[node] == index[node]:
                    comp = []
                    while True:
                        w = stack.pop()
                        on_stack.discard(w)
                        comp.append(w)
                        if w == node:
                            break
                    if len(comp) > 1:
                        result.append(sorted(comp))
    return sorted(result, key=len, reverse=True)


# ---------------------------------------------------------------- reporting

def table(rows: list[tuple], headers: tuple) -> str:
    rows = [tuple(str(c) for c in r) for r in rows]
    widths = [max(len(h), *(len(r[i]) for r in rows)) if rows else len(h) for i, h in enumerate(headers)]
    fmt = "  ".join(f"{{:{'>' if i < len(headers) - 1 else '<'}{w}}}" for i, w in enumerate(widths))
    return "\n".join([fmt.format(*headers), *(fmt.format(*r) for r in rows)])


def top_by(facts: list[FileFacts], key, n: int, label: str) -> str:
    ranked = sorted((f for f in facts if key(f)), key=key, reverse=True)[:n]
    if not ranked:
        return "(none)"
    return table([(key(f), f.lines, f.path) for f in ranked], (label, "lines", "file"))


def dependency_report(root: Path, facts: list[FileFacts], all_files: list[str], depth: int, top: int) -> list[str]:
    by_path = {f.path: f for f in facts}
    js_files = {f.path for f in facts if f.path.endswith(JS_EXTS)}
    py_files = [f.path for f in facts if f.lang == "Python"]
    index, file_to_module = python_index(py_files)
    configs = load_ts_configs(root, all_files)
    gomods = go_modules(root, all_files)
    dart_pkgs = dart_packages(root, all_files)
    dart_files = {f.path for f in facts if f.lang == "Dart"}

    file_graph: dict[str, set[str]] = defaultdict(set)
    unit_edges: dict[tuple[str, str], list[tuple[str, str]]] = defaultdict(list)
    unresolved = []
    for f in facts:
        if f.generated:
            continue
        targets: list[tuple[str, bool]] = []
        if f.path in js_files:
            for spec in JS_IMPORT.findall(f.text):
                ext = posixpath.splitext(spec)[1]
                if ext and ext not in JS_EXTS and not ext[1:].isdigit():
                    continue  # stylesheet, image, JSON and other non-code imports
                hit = resolve_js(f.path, spec, js_files, configs)
                if hit == "?":
                    unresolved.append(f"{f.path} -> {spec}")
                elif hit:
                    targets.append((hit, False))
        elif f.lang == "Python":
            targets = [(t, False) for t in python_imports(f.path, f.text, index, file_to_module)]
        elif f.lang == "Go" and gomods:
            targets = [(d, True) for d in go_imports(f.text, gomods)]
        elif f.lang == "Dart":
            targets = [(t, False) for t in dart_imports(f.path, f.text, dart_pkgs, dart_files)]
        src_unit = unit_of(f.path, depth)
        for target, is_dir in targets:
            if target == f.path:
                continue
            if not is_dir:
                file_graph[f.path].add(target)
            tgt_unit = unit_of(target, depth, is_dir)
            if tgt_unit != src_unit:
                unit_edges[(src_unit, tgt_unit)].append((f.path, target))

    out = ["## Dependencies (heuristic: Python, JS/TS, Go, Dart)", ""]
    if not file_graph and not unit_edges:
        out += ["No internal imports resolved (no supported language, or imports use a scheme this script can't follow).", ""]
        return out
    out += [f"File-to-file import edges: {sum(len(v) for v in file_graph.values())} · "
            f"unit-to-unit edges: {len(unit_edges)} (units = first {depth} directory levels) · "
            f"unresolved relative imports: {len(unresolved)}", ""]
    for example in unresolved[:5]:
        out.append(f"  unresolved: {example}")
    if unresolved:
        out.append("")

    unit_graph: dict[str, set[str]] = defaultdict(set)
    for s, t in unit_edges:
        unit_graph[s].add(t)
    cycles = strongly_connected(unit_graph)
    out += ["### Cycles between units", ""]
    if not cycles:
        out.append("(none)")
    for comp in cycles:
        members = set(comp)
        out.append(f"- cycle of {len(comp)}: {', '.join(comp)}")
        for (s, t), pairs in sorted(unit_edges.items()):
            if s in members and t in members:
                out.append(f"    {s} -> {t}  ({len(pairs)} imports, e.g. {pairs[0][0]} -> {pairs[0][1]})")
    out.append("")

    file_cycles = strongly_connected(file_graph)
    out += [f"### Cycles between files: {len(file_cycles)}", ""]
    for comp in file_cycles[:5]:
        shown = ", ".join(comp[:8]) + (f", … (+{len(comp) - 8})" if len(comp) > 8 else "")
        out.append(f"- {len(comp)} files: {shown}")
    out.append("")

    fan_in, fan_out = Counter(), Counter()
    for s, t in unit_edges:
        fan_out[s] += 1
        fan_in[t] += 1
    out += ["### Unit fan-in / fan-out (distinct units)", ""]
    units = sorted(set(fan_in) | set(fan_out), key=lambda u: (fan_in[u] + fan_out[u]), reverse=True)[:top]
    out += [table([(fan_in[u], fan_out[u], u) for u in units], ("in", "out", "unit")), ""]

    imported_by = Counter()
    for targets in file_graph.values():
        imported_by.update(targets)
    out += ["### Most-imported files", ""]
    out += [table([(n, by_path[p].lines if p in by_path else "", p) for p, n in imported_by.most_common(top)],
                  ("importers", "lines", "file")), ""]
    out += ["### Files importing the most internal files", ""]
    heavy = sorted(file_graph.items(), key=lambda kv: len(kv[1]), reverse=True)[:top]
    out += [table([(len(t), by_path[p].lines, p) for p, t in heavy], ("imports", "lines", "file")), ""]
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Read-only codebase inventory for the strict_review skill.")
    ap.add_argument("root", nargs="?", default=".")
    ap.add_argument("--top", type=int, default=15, help="rows per ranking (default 15)")
    ap.add_argument("--depth", type=int, default=2, help="directory levels that define a unit (default 2)")
    ap.add_argument("--exclude", action="append", default=[], metavar="GLOB", help="skip paths matching GLOB")
    ap.add_argument("--no-deps", action="store_true", help="skip the dependency graph")
    args = ap.parse_args()
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except AttributeError:
        pass

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"not a directory: {root}", file=sys.stderr)
        return 2
    all_files, method = list_files(root)
    all_files = [p for p in all_files if not any(fnmatch.fnmatch(p, g) for g in args.exclude)]

    facts = []
    for p in all_files:
        lang = LANGUAGES.get(posixpath.splitext(p)[1].lower())
        text = read_text(root / p) if lang else None
        if text is not None:
            facts.append(FileFacts(p, lang, text))
    if not facts:
        print(f"# Inventory: {root}\n\nNo source files found ({method}, {len(all_files)} files listed).")
        return 0

    real = [f for f in facts if not f.generated]
    source = [f for f in real if not f.is_test]
    tests = [f for f in real if f.is_test]
    src_lines = sum(f.lines for f in source)
    test_lines = sum(f.lines for f in tests)
    out = [
        f"# Inventory: {root}",
        "",
        f"Files listed via {method}: {len(all_files)} · source files: {len(source)} ({src_lines} lines) · "
        f"test files: {len(tests)} ({test_lines} lines) · generated (excluded below): {len(facts) - len(real)}",
        f"Test-to-source line ratio: {test_lines / src_lines:.2f}" if src_lines else "",
        "",
        "## Languages", "",
    ]
    by_lang = defaultdict(lambda: [0, 0])
    for f in real:
        by_lang[f.lang][0] += 1
        by_lang[f.lang][1] += f.lines
    total = sum(v[1] for v in by_lang.values()) or 1
    out += [table([(v[0], v[1], f"{100 * v[1] / total:.0f}%", lang)
                   for lang, v in sorted(by_lang.items(), key=lambda kv: -kv[1][1])],
                  ("files", "lines", "share", "language")), ""]

    sizes = sorted(f.lines for f in source) or [0]
    bands = [(">2000", lambda n: n > 2000), ("1000-2000", lambda n: 1000 < n <= 2000),
             ("500-1000", lambda n: 500 < n <= 1000), ("<=500", lambda n: n <= 500)]
    out += ["## Size distribution (non-test source)", "",
            "  ".join(f"{label}: {sum(1 for n in sizes if test(n))}" for label, test in bands)
            + f"  · median {statistics.median(sizes):.0f} · p90 {sizes[int(0.9 * (len(sizes) - 1))]} · max {sizes[-1]}", ""]
    largest = sorted(real, key=lambda f: -f.lines)[:args.top]
    out += ["## Largest files", "",
            table([(f.lines, "test" if f.is_test else "", f.path) for f in largest], ("lines", "kind", "file")), ""]

    mass = defaultdict(lambda: [0, 0])
    for f in source:
        u = unit_of(f.path, args.depth)
        mass[u][0] += 1
        mass[u][1] += f.lines
    ranked_units = sorted(mass.items(), key=lambda kv: -kv[1][1])
    out += [f"## Mass by unit (first {args.depth} directory levels, non-test)", "",
            table([(v[1], v[0], u) for u, v in ranked_units[:args.top]], ("lines", "files", "unit")), ""]
    biggest, (_, biggest_lines) = ranked_units[0]
    if len(source) >= 20 and biggest_lines > 0.5 * src_lines:
        out += [f"Hint: {biggest} holds {100 * biggest_lines / src_lines:.0f}% of the source, so the unit graph "
                f"below says little. Rerun with --depth {args.depth + 1} (or deeper) to see inside it.", ""]

    marker_total = sum(f.markers for f in real)
    out += [f"## Debt markers (TODO/FIXME/HACK/XXX): {marker_total}", "",
            top_by(real, lambda f: f.markers, args.top, "markers"), ""]
    kinds = Counter()
    for f in real:
        kinds.update(f.suppressions)
    out += [f"## Suppressions: {sum(kinds.values())}", ""]
    if kinds:
        out += [", ".join(f"{k} ×{n}" for k, n in kinds.most_common()), ""]
    out += [top_by(real, lambda f: sum(f.suppressions.values()), args.top, "count"), ""]
    out += [f"## Type-system escape hatches: {sum(f.escapes for f in real)} "
            "(any/cast/!/unwrap/dynamic/interface{}… per language)", "",
            top_by(real, lambda f: f.escapes, args.top, "count"), ""]
    out += [f"## Deep indentation (lines at >= {DEEP_LEVELS} levels; nesting proxy)", "",
            top_by(real, lambda f: f.deep, args.top, "deep"), ""]

    if not args.no_deps:
        out += dependency_report(root, facts, all_files, args.depth, args.top)
    out.append("Every figure above is a lead to read, not a finding.")
    print("\n".join(out))
    return 0


